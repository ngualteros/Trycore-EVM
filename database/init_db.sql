
CREATE TABLE IF NOT EXISTS projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    CONSTRAINT ck_projects_name_not_blank CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE IF NOT EXISTS activities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id INTEGER NOT NULL,
    name VARCHAR(150) NOT NULL,
    bac NUMERIC(16,2) NOT NULL,
    planned_progress_pct NUMERIC(5,2) NOT NULL,
    actual_progress_pct NUMERIC(5,2) NOT NULL,
    actual_cost NUMERIC(16,2) NOT NULL,
    CONSTRAINT fk_activities_project FOREIGN KEY (project_id)
        REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT ck_activities_name_not_blank CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_activities_bac_range CHECK (bac >= 0 AND bac <= 99999999999999.99),
    CONSTRAINT ck_activities_actual_cost_range
        CHECK (actual_cost >= 0 AND actual_cost <= 99999999999999.99),
    CONSTRAINT ck_activities_planned_progress_range
        CHECK (planned_progress_pct >= 0 AND planned_progress_pct <= 100),
    CONSTRAINT ck_activities_actual_progress_range
        CHECK (actual_progress_pct >= 0 AND actual_progress_pct <= 100)
);

CREATE INDEX IF NOT EXISTS ix_activities_project_id ON activities(project_id);
